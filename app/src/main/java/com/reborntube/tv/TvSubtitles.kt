package com.reborntube.tv

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.net.HttpURLConnection
import java.net.URL
import java.util.Locale

data class TvSubtitleCue(val startMs: Long, val endMs: Long, val text: String)

fun subtitleTracks(info: StreamInfo): List<SubtitlesStream> {
    val deviceLanguage = Locale.getDefault().language
    return info.subtitles
        .filter { it.format == MediaFormat.VTT || it.format == MediaFormat.TTML }
        .groupBy { it.languageTag + it.isAutoGenerated }
        .map { (_, variants) -> variants.firstOrNull { it.format == MediaFormat.VTT } ?: variants.first() }
        .sortedWith(
            compareBy<SubtitlesStream>(
                { it.isAutoGenerated },
                { !it.languageTag.startsWith(deviceLanguage) },
                { it.displayLanguageName }
            )
        )
}

suspend fun loadTvSubtitles(stream: SubtitlesStream): List<TvSubtitleCue> = withContext(Dispatchers.IO) {
    val connection = URL(stream.content).openConnection() as HttpURLConnection
    connection.connectTimeout = 15_000
    connection.readTimeout = 15_000
    connection.setRequestProperty(
        "User-Agent",
        "Mozilla/5.0 (Linux; Android 11; Fire TV) AppleWebKit/537.36 Chrome/131.0 Safari/537.36"
    )
    try {
        val text = connection.inputStream.bufferedReader().use { it.readText() }
        val cues = if (text.trimStart().startsWith("WEBVTT") || stream.format == MediaFormat.VTT) {
            parseVtt(text)
        } else {
            parseTtml(text)
        }.sortedBy { it.startMs }
        if (stream.isAutoGenerated) dedupe(cues) else cues
    } finally {
        connection.disconnect()
    }
}

fun tvSubtitleAt(cues: List<TvSubtitleCue>, positionMs: Long): String? {
    var low = 0
    var high = cues.lastIndex
    var index = -1
    while (low <= high) {
        val middle = (low + high) ushr 1
        if (cues[middle].startMs <= positionMs) {
            index = middle
            low = middle + 1
        } else {
            high = middle - 1
        }
    }
    var candidate = index
    var checked = 0
    while (candidate >= 0 && checked < 4) {
        if (positionMs < cues[candidate].endMs) return cues[candidate].text
        candidate--
        checked++
    }
    return null
}

private val vttTiming = Regex(
    "((?:\\d+:)?\\d{1,2}:\\d{2}[.,]\\d{1,3})\\s*-->\\s*((?:\\d+:)?\\d{1,2}:\\d{2}[.,]\\d{1,3})"
)

private fun parseVtt(text: String): List<TvSubtitleCue> {
    val cues = ArrayList<TvSubtitleCue>()
    val blocks = text.replace("\r\n", "\n").split(Regex("\n\n+"))
    for (block in blocks) {
        val lines = block.split("\n")
        val timingLine = lines.indexOfFirst { vttTiming.containsMatchIn(it) }
        if (timingLine < 0) continue
        val times = vttTiming.find(lines[timingLine]) ?: continue
        val start = parseClock(times.groupValues[1])
        val end = parseClock(times.groupValues[2])
        val body = cleanSubtitleText(lines.drop(timingLine + 1).joinToString("\n"))
        if (body.isNotEmpty() && end > start) cues += TvSubtitleCue(start, end, body)
    }
    return cues
}

private fun parseTtml(text: String): List<TvSubtitleCue> {
    val cues = ArrayList<TvSubtitleCue>()
    val paragraph = Regex("<p\\b([^>]*)>(.*?)</p>", RegexOption.DOT_MATCHES_ALL)
    for (match in paragraph.findAll(text)) {
        val attributes = match.groupValues[1]
        val begin = attribute(attributes, "begin")
        val end = attribute(attributes, "end")
        val duration = attribute(attributes, "dur")
        val startTicks = attribute(attributes, "t")
        val durationTicks = attribute(attributes, "d")
        val start: Long
        val finish: Long
        if (begin != null) {
            start = parseTtmlTime(begin)
            finish = if (end != null) parseTtmlTime(end)
            else start + (duration?.let(::parseTtmlTime) ?: 0L)
        } else if (startTicks != null) {
            start = startTicks.toLongOrNull() ?: continue
            finish = start + (durationTicks?.toLongOrNull() ?: 0L)
        } else {
            continue
        }
        val body = cleanSubtitleText(match.groupValues[2].replace(Regex("<br\\s*/?>"), "\n"))
        if (body.isNotEmpty() && finish > start) cues += TvSubtitleCue(start, finish, body)
    }
    return cues
}

private fun attribute(attributes: String, name: String): String? =
    Regex("\\b$name=\"([^\"]*)\"").find(attributes)?.groupValues?.get(1)

private fun parseClock(value: String): Long {
    val parts = value.replace(',', '.').split(":")
    val seconds = parts.last().toDouble()
    val minutes = if (parts.size >= 2) parts[parts.lastIndex - 1].toLong() else 0L
    val hours = if (parts.size >= 3) parts[parts.lastIndex - 2].toLong() else 0L
    return (hours * 3600 + minutes * 60) * 1000 + (seconds * 1000).toLong()
}

private fun parseTtmlTime(value: String): Long = when {
    value.contains(":") -> parseClock(value)
    value.endsWith("ms") -> value.dropLast(2).toDouble().toLong()
    value.endsWith("s") -> (value.dropLast(1).toDouble() * 1000).toLong()
    else -> value.toDouble().toLong()
}

private fun cleanSubtitleText(raw: String): String =
    raw.replace(Regex("<[^>]+>"), "")
        .replace("&amp;", "&")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&#39;", "'")
        .replace("&apos;", "'")
        .replace("&nbsp;", " ")
        .split("\n")
        .map { it.trim() }
        .filter { it.isNotEmpty() }
        .joinToString("\n")

private fun dedupe(cues: List<TvSubtitleCue>): List<TvSubtitleCue> {
    val output = ArrayList<TvSubtitleCue>()
    var previous = emptySet<String>()
    for (cue in cues) {
        if (cue.endMs - cue.startMs < 80) continue
        val lines = cue.text.split("\n")
        val fresh = lines.filterNot { it in previous }
        previous = lines.toSet()
        if (fresh.isNotEmpty()) output += cue.copy(text = fresh.joinToString("\n"))
    }
    return output
}
